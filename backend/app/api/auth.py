"""Local-network authentication.

Access token: ``STRIX_AUTH_TOKEN`` (generated by the installer). Clients may
send it as ``Authorization: Bearer <token>`` or exchange it once at
``POST /api/auth/login`` for a signed, HttpOnly, SameSite=Strict session
cookie (used by the browser for REST, MJPEG and WebSocket requests).

If auth is enabled but no token is configured, a random token is generated
and written to ``<data_dir>/auth_token`` (mode 0600) — never logged.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import logging
import os
import secrets
import time
from pathlib import Path

from fastapi import HTTPException, Request, WebSocket

from app.config.settings import Settings
from app.core.ratelimit import SlidingWindowLimiter

log = logging.getLogger(__name__)

COOKIE_NAME = "strix_session"


class AuthManager:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.enabled = settings.auth_enabled
        self.token = self._resolve_token() if self.enabled else ""
        secret = settings.session_secret.get_secret_value() if settings.session_secret else ""
        # Derive the cookie key from the access token so rotating the token
        # invalidates every existing session.
        self._key = hashlib.sha256(("strix-session:" + (secret or self.token)).encode()).digest()
        self._login_limiters: dict[str, SlidingWindowLimiter] = {}

    def _resolve_token(self) -> str:
        if self.settings.auth_token and self.settings.auth_token.get_secret_value().strip():
            return self.settings.auth_token.get_secret_value().strip()
        path: Path = self.settings.data_dir / "auth_token"
        try:
            existing = path.read_text().strip()
            if existing:
                log.warning("STRIX_AUTH_TOKEN not set; using token stored in %s", path)
                return existing
        except FileNotFoundError:
            pass
        token = secrets.token_urlsafe(24)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(token + "\n")
        log.warning("STRIX_AUTH_TOKEN not set; generated a new access token in %s (mode 0600)", path)
        return token

    # ------------------------------------------------------------ tokens
    def check_token(self, candidate: str) -> bool:
        return bool(candidate) and hmac.compare_digest(candidate.encode(), self.token.encode())

    def make_cookie(self) -> str:
        payload = json.dumps({"exp": time.time() + self.settings.session_ttl_hours * 3600, "n": secrets.token_hex(8)},
                             separators=(",", ":")).encode()
        body = base64.urlsafe_b64encode(payload).decode().rstrip("=")
        sig = hmac.new(self._key, body.encode(), hashlib.sha256).hexdigest()
        return f"{body}.{sig}"

    def verify_cookie(self, value: str | None) -> bool:
        if not value or "." not in value:
            return False
        body, sig = value.rsplit(".", 1)
        expected = hmac.new(self._key, body.encode(), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(sig, expected):
            return False
        try:
            payload = json.loads(base64.urlsafe_b64decode(body + "=" * (-len(body) % 4)))
            return float(payload["exp"]) > time.time()
        except Exception:
            return False

    def login_allowed(self, client: str) -> bool:
        lim = self._login_limiters.setdefault(client, SlidingWindowLimiter(10, 60.0))
        return lim.check().allowed

    # ------------------------------------------------------------ checks
    def is_authenticated(self, headers, cookies) -> bool:
        if not self.enabled:
            return True
        auth = headers.get("authorization", "")
        if auth.lower().startswith("bearer ") and self.check_token(auth[7:].strip()):
            return True
        return self.verify_cookie(cookies.get(COOKIE_NAME))

    def require(self, request: Request) -> None:
        if not self.is_authenticated(request.headers, request.cookies):
            raise HTTPException(status_code=401, detail={"code": "unauthorized", "message": "authentication required"})

    def websocket_ok(self, ws: WebSocket) -> bool:
        if not self.enabled:
            return True
        if self.is_authenticated(ws.headers, ws.cookies):
            return True
        token = ws.query_params.get("token")
        return bool(token) and self.check_token(token)


def origin_allowed(ws: WebSocket, extra_origins: list[str]) -> bool:
    """Reject cross-site WebSocket hijacking: Origin must match Host (or be allow-listed)."""
    origin = ws.headers.get("origin")
    if not origin:
        return True  # non-browser client
    host = ws.headers.get("host", "")
    if origin in extra_origins:
        return True
    return origin.split("://", 1)[-1].rstrip("/") == host
