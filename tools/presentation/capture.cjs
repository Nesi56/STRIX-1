const { chromium } = require("playwright");
const OUT = process.argv[2];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1920, height: 960 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  await p.goto((process.env.STRIX_URL || "http://127.0.0.1:8000") + "/");
  await p.fill("input[type=password]", process.env.STRIX_TOKEN || "");
  await p.keyboard.press("Enter");
  await p.waitForSelector("text=Camera Servo");
  const api = (path, body) => p.evaluate(async ([u, bd]) => (await fetch(u, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(bd ?? {}) })).status, [path, body]);
  await api("/api/servo/disarm");
  await p.evaluate(() => fetch("/api/agent/history", { method: "DELETE" }));
  await p.reload(); await p.waitForSelector("text=Camera Servo");
  const sec = (txt) => p.locator("section").filter({ has: p.locator(`h2:text-is("${txt}"), span:text-is("${txt}")`) }).first();
  const video = p.locator("canvas.max-h-full").locator("xpath=..");
  const shot = async (loc, name) => { await loc.screenshot({ path: `${OUT}/${name}.png` }); console.log("shot", name); };
  const ask = async (t) => { const bx = p.locator("input[aria-label='Message for Qwen']"); await bx.fill(t); await bx.press("Enter"); };

  await api("/api/demo/scene", { scene: "cups" });
  const t0 = Date.now(); const at = async (s) => { const w = t0 + s * 1000 - Date.now(); if (w > 0) await sleep(w); };
  await at(3.0);
  await shot(video, "sees");
  await shot(sec("STATUS"), "status");
  await p.getByRole("button", { name: "Drone", exact: true }).click();
  await sleep(1500);
  await shot(sec("Live 3D"), "drone3d");
  await p.getByRole("button", { name: "World", exact: true }).click();
  await p.getByRole("button", { name: /Enable control/ }).click();
  await at(11.0);
  await shot(video, "hidden");
  await shot(sec("Live 3D"), "world3d");
  await ask("look up 20 degrees");
  await at(15.5);
  await shot(p.locator("section").filter({ has: p.locator("button:text-is('Recordings')") }).first(), "chat_lookup");
  await shot(sec("Camera Servo"), "servo");
  await p.getByRole("button", { name: /Center/ }).first().click();
  await at(20.0);
  await api("/api/servo/nudge", { up_deg: 45 });
  await at(23.0);
  await shot(sec("Memory"), "memory_remembered");
  await ask("where is the ball?");
  await at(29.0);
  await shot(p.locator("section").filter({ has: p.locator("button:text-is('Recordings')") }).first(), "chat_where");
  await at(32.5);
  await shot(video, "reveal");
  await shot(sec("Memory"), "memory_reveal");
  await p.screenshot({ path: `${OUT}/console.png` });
  await b.close();
})();
